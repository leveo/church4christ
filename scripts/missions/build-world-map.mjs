// Generates public/images/missions/world-land.svg: the land outline drawn behind
// the public mission map, as one SVG path in an equirectangular projection
// (1000 x 500, longitude -180..180 left to right, latitude 90..-90 top to bottom).
// The page uses it as a CSS mask, so its color comes from the design tokens, and
// places pins with the same formula (src/lib/missionMap.ts). No map library ships
// to the browser or the Worker.
//
// Source: world-atlas 2.x `land-110m.json` (ISC license, derived from Natural
// Earth public-domain data). Run once when the outline should change:
//
//   npm install --no-save d3-geo@3 topojson-client@3 world-atlas@2
//   node scripts/missions/build-world-map.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const land = require('world-atlas/land-110m.json');
const WIDTH = 1000;
const HEIGHT = 500;
const projection = geoEquirectangular().scale(WIDTH / (2 * Math.PI)).translate([WIDTH / 2, HEIGHT / 2]).precision(0.1);
const raw = geoPath(projection)(feature(land, land.objects.land));
// One decimal place is well under a pixel at this size and keeps the file small.
const path = raw.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
const out = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}">
<!-- Generated by scripts/missions/build-world-map.mjs from world-atlas land-110m (ISC license; Natural Earth public-domain data). -->
<path d="${path}"/>
</svg>
`;
mkdirSync(new URL('../../public/images/missions/', import.meta.url), { recursive: true });
writeFileSync(new URL('../../public/images/missions/world-land.svg', import.meta.url), out);
console.log(`wrote public/images/missions/world-land.svg (${out.length} bytes)`);
