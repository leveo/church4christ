CREATE OR REPLACE FUNCTION identity_source_records_insert_unlinked() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.linked_person_id IS NOT NULL OR NEW.provisional_person_id IS NOT NULL OR NEW.state<>'unlinked' OR NOT EXISTS (
    SELECT 1 FROM identity_observations o WHERE o.id=NEW.observation_id AND o.campus_id=NEW.campus_id
      AND o.source=NEW.source AND o.source_key=NEW.source_record_key AND o.status='provisional' AND o.linked_person_id IS NULL
  ) OR NOT EXISTS (
    SELECT 1 FROM identity_source_key_config k WHERE k.singleton_id=1 AND k.key_id=NEW.source_key_id
  ) THEN RAISE EXCEPTION 'identity_source_insert_invalid'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER identity_source_records_insert_unlinked BEFORE INSERT ON identity_source_records FOR EACH ROW EXECUTE FUNCTION identity_source_records_insert_unlinked();

CREATE OR REPLACE FUNCTION identity_source_records_identity_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.campus_id<>NEW.campus_id OR OLD.source<>NEW.source OR OLD.source_record_key<>NEW.source_record_key
    OR OLD.source_key_id<>NEW.source_key_id OR OLD.observation_id<>NEW.observation_id OR OLD.attachment_policy<>NEW.attachment_policy
  THEN RAISE EXCEPTION 'identity_source_identity_immutable'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER identity_source_records_identity_immutable BEFORE UPDATE OF campus_id,source,source_record_key,source_key_id,observation_id,attachment_policy ON identity_source_records FOR EACH ROW EXECUTE FUNCTION identity_source_records_identity_immutable();

CREATE OR REPLACE FUNCTION identity_source_records_version_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.version<>OLD.version OR NEW.source_digest<>OLD.source_digest) AND (
    OLD.state='linked' OR NEW.version<>OLD.version+1 OR NEW.source_digest=OLD.source_digest OR NEW.state<>'unlinked'
    OR NEW.linked_person_id IS NOT NULL OR OLD.provisional_person_id IS NOT NULL OR EXISTS (
      SELECT 1 FROM identity_source_provisional_operations op
      WHERE op.source_record_id=OLD.id AND op.source_version=OLD.version AND op.source_digest=OLD.source_digest
    )
  ) THEN RAISE EXCEPTION 'identity_source_version_conflict'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER identity_source_records_version_guard BEFORE UPDATE OF version,source_digest ON identity_source_records FOR EACH ROW EXECUTE FUNCTION identity_source_records_version_guard();

CREATE OR REPLACE FUNCTION identity_claim_operation_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM identity_source_records s JOIN identity_observations o ON o.id=s.observation_id
    JOIN contact_points cp ON cp.id=NEW.expected_contact_point_id
    WHERE s.id=NEW.source_record_id AND s.campus_id=NEW.campus_id AND s.attachment_policy='signed_in_or_claim'
      AND s.state='unlinked' AND s.version=NEW.expected_source_version AND s.source_digest=NEW.expected_source_digest
      AND cp.kind='email' AND cp.normalized_value=o.normalized_email
  ) OR NOT EXISTS (
    SELECT 1 FROM identity_challenges c WHERE c.id=NEW.challenge_id AND c.campus_id=NEW.campus_id
      AND c.purpose='claim' AND c.contact_point_id=NEW.expected_contact_point_id AND c.consumed_at IS NULL AND c.superseded_at IS NULL
      AND c.expires_at>datetime('now') AND (NEW.expected_owner_person_id IS NULL OR c.person_id=NEW.expected_owner_person_id)
  ) OR (NEW.expected_owner_person_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM verified_contact_owners v JOIN people p ON p.id=v.person_id
    JOIN campus_memberships cm ON cm.person_id=p.id AND cm.campus_id=NEW.campus_id AND cm.active=1
    LEFT JOIN person_merge_redirects r ON r.loser_person_id=p.id
    WHERE v.contact_point_id=NEW.expected_contact_point_id AND v.person_id=NEW.expected_owner_person_id
      AND NEW.expected_owner_generation=COALESCE((SELECT MAX(generation) FROM contact_owner_mutation_claims m WHERE m.contact_point_id=v.contact_point_id),0)
      AND (SELECT COUNT(*) FROM person_contact_links l WHERE l.contact_point_id=v.contact_point_id AND l.ended_at IS NULL)=1
      AND NOT EXISTS (SELECT 1 FROM household_contact_links h WHERE h.campus_id=NEW.campus_id AND h.contact_point_id=v.contact_point_id AND h.ended_at IS NULL)
      AND p.active=1 AND p.deleted_at IS NULL AND p.identity_state='active' AND p.auth_disabled_at IS NULL AND r.loser_person_id IS NULL
  )) OR (NEW.expected_owner_person_id IS NULL AND EXISTS (
    SELECT 1 FROM verified_contact_owners v JOIN people p ON p.id=v.person_id
    JOIN campus_memberships cm ON cm.person_id=p.id AND cm.campus_id=NEW.campus_id AND cm.active=1
    LEFT JOIN person_merge_redirects r ON r.loser_person_id=p.id
    WHERE v.contact_point_id=NEW.expected_contact_point_id
      AND (SELECT COUNT(*) FROM person_contact_links l WHERE l.contact_point_id=v.contact_point_id AND l.ended_at IS NULL)=1
      AND NOT EXISTS (SELECT 1 FROM household_contact_links h WHERE h.campus_id=NEW.campus_id AND h.contact_point_id=v.contact_point_id AND h.ended_at IS NULL)
      AND p.active=1 AND p.deleted_at IS NULL AND p.identity_state='active' AND p.auth_disabled_at IS NULL AND r.loser_person_id IS NULL
  )) THEN RAISE EXCEPTION 'identity_claim_binding_invalid'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER identity_claim_operation_insert_guard BEFORE INSERT ON identity_claim_operations FOR EACH ROW EXECUTE FUNCTION identity_claim_operation_insert_guard();

