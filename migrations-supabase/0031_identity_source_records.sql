CREATE OR REPLACE FUNCTION identity_source_provisional_operation_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM identity_source_records WHERE id=NEW.source_record_id FOR UPDATE;
  PERFORM pg_advisory_xact_lock(hashtextextended(lock_key,0)) FROM (
    SELECT 'email:'||o.normalized_email AS lock_key FROM identity_source_records s
      JOIN identity_observations o ON o.id=s.observation_id
      WHERE s.id=NEW.source_record_id AND o.normalized_email IS NOT NULL
    UNION ALL
    SELECT 'phone:'||o.normalized_phone AS lock_key FROM identity_source_records s
      JOIN identity_observations o ON o.id=s.observation_id
      WHERE s.id=NEW.source_record_id AND o.normalized_phone IS NOT NULL
  ) contact_locks ORDER BY lock_key;
  IF NOT EXISTS (
    SELECT 1 FROM identity_source_records s JOIN identity_observations o ON o.id=s.observation_id
    WHERE s.id=NEW.source_record_id AND s.campus_id=NEW.campus_id AND s.source IN ('group','newcomer','import')
      AND s.attachment_policy='observation_only' AND s.state='unlinked' AND s.linked_person_id IS NULL
      AND s.provisional_person_id IS NULL AND s.version=NEW.source_version AND s.source_digest=NEW.source_digest
      AND o.status='provisional' AND o.linked_person_id IS NULL
  ) OR EXISTS (SELECT 1 FROM people p WHERE p.id=NEW.reserved_person_id)
  THEN RAISE EXCEPTION 'identity_source_provisional_reservation_invalid'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER identity_source_provisional_operation_insert_guard BEFORE INSERT ON identity_source_provisional_operations FOR EACH ROW EXECUTE FUNCTION identity_source_provisional_operation_insert_guard();

CREATE OR REPLACE FUNCTION identity_source_provisional_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF COALESCE(OLD.provisional_person_id,0)<>COALESCE(NEW.provisional_person_id,0) AND (
    OLD.provisional_person_id IS NOT NULL OR NEW.provisional_person_id IS NULL OR NEW.linked_person_id IS NOT NULL
    OR NEW.state<>'unlinked' OR NEW.source NOT IN ('group','newcomer','import') OR NEW.attachment_policy<>'observation_only'
    OR NOT EXISTS (SELECT 1 FROM identity_source_provisional_operations op WHERE op.source_record_id=NEW.id
      AND op.campus_id=NEW.campus_id AND op.source_version=NEW.version AND op.source_digest=NEW.source_digest
      AND op.reserved_person_id=NEW.provisional_person_id)
    OR NOT EXISTS (SELECT 1 FROM people p WHERE p.id=NEW.provisional_person_id AND p.active=0 AND p.deleted_at IS NULL
      AND p.identity_state='provisional' AND p.auth_disabled_at IS NOT NULL AND p.provisional_source=NEW.source)
    OR NOT EXISTS (SELECT 1 FROM person_contact_links l JOIN contact_points cp ON cp.id=l.contact_point_id
      JOIN identity_observations o ON o.id=NEW.observation_id WHERE l.person_id=NEW.provisional_person_id AND l.ended_at IS NULL
        AND l.notification_enabled=1 AND ((cp.kind='email' AND cp.normalized_value=o.normalized_email) OR (cp.kind='phone' AND cp.normalized_value=o.normalized_phone)))
    OR EXISTS (SELECT 1 FROM person_contact_links l JOIN verified_contact_owners v ON v.contact_point_id=l.contact_point_id
      WHERE l.person_id=NEW.provisional_person_id AND l.ended_at IS NULL)
    OR EXISTS (SELECT 1 FROM person_contact_links candidate JOIN person_contact_links existing
      ON existing.contact_point_id=candidate.contact_point_id
      WHERE candidate.person_id=NEW.provisional_person_id AND candidate.ended_at IS NULL
        AND existing.person_id<>NEW.provisional_person_id AND existing.ended_at IS NULL)
    OR EXISTS (SELECT 1 FROM person_contact_links candidate JOIN household_contact_links household
      ON household.contact_point_id=candidate.contact_point_id
      WHERE candidate.person_id=NEW.provisional_person_id AND candidate.ended_at IS NULL
        AND household.ended_at IS NULL)
  ) THEN RAISE EXCEPTION 'identity_source_provisional_invalid'; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER identity_source_provisional_guard BEFORE UPDATE OF provisional_person_id ON identity_source_records FOR EACH ROW EXECUTE FUNCTION identity_source_provisional_guard();

