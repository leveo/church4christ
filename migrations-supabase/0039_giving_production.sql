-- Production Giving (PostgreSQL only; the giving tables do not exist on D1).
-- Adds live/test separation, charge-level money facts (paid date, refunds, Stripe
-- charge id), ACH and dispute states, per-mode Stripe customers, richer funds,
-- and the durable annual-statement outbox. Card and bank details are never stored.

-- ── gifts ─────────────────────────────────────────────────────────────────────
ALTER TABLE gifts ADD COLUMN livemode BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE gifts ADD COLUMN paid_at TEXT;               -- UTC 'YYYY-MM-DD HH:MM:SS' from the Stripe object
ALTER TABLE gifts ADD COLUMN refunded_cents INTEGER NOT NULL DEFAULT 0 CHECK (refunded_cents >= 0);
ALTER TABLE gifts ADD COLUMN stripe_charge_id TEXT;

-- Manual check/cash gifts are real money; everything Stripe wrote before this
-- migration came from the test-only runtime and stays livemode = false.
UPDATE gifts SET livemode = true WHERE method IN ('check', 'cash');
UPDATE gifts SET paid_at = created_at WHERE method = 'card' AND paid_at IS NULL;
UPDATE gifts SET refunded_cents = amount_cents WHERE status = 'refunded';

ALTER TABLE gifts DROP CONSTRAINT gifts_method_check;
ALTER TABLE gifts ADD CONSTRAINT gifts_method_check
  CHECK (method IN ('card', 'us_bank_account', 'check', 'cash'));
ALTER TABLE gifts DROP CONSTRAINT gifts_status_check;
ALTER TABLE gifts ADD CONSTRAINT gifts_status_check
  CHECK (status IN ('pending', 'succeeded', 'failed', 'refunded', 'disputed'));
CREATE INDEX gifts_charge ON gifts(stripe_charge_id) WHERE stripe_charge_id IS NOT NULL;
CREATE INDEX gifts_livemode_status ON gifts(livemode, status);

-- ── recurring_gifts ───────────────────────────────────────────────────────────
ALTER TABLE recurring_gifts ADD COLUMN livemode BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE recurring_gifts DROP CONSTRAINT recurring_gifts_interval_check;
ALTER TABLE recurring_gifts ADD CONSTRAINT recurring_gifts_interval_check
  CHECK ("interval" IN ('week', 'month', 'year'));

-- ── Stripe customers, one per person per mode ─────────────────────────────────
-- people.stripe_customer_id stays as a legacy test-mode read fallback only.
-- campus_id records where the customer was created; it is informational and the
-- table is deliberately NOT campus-scoped (a donor is one Stripe customer).
CREATE TABLE stripe_customers (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  person_id integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
  livemode BOOLEAN NOT NULL,
  customer_id TEXT NOT NULL UNIQUE,
  campus_id INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (person_id, livemode)
);

-- ── funds ─────────────────────────────────────────────────────────────────────
ALTER TABLE fund_i18n ADD COLUMN description TEXT NOT NULL DEFAULT '';
ALTER TABLE funds ADD COLUMN is_default BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE funds ADD COLUMN tax_deductible BOOLEAN NOT NULL DEFAULT true;
CREATE UNIQUE INDEX funds_one_default_per_campus ON funds(campus_id) WHERE is_default;

-- ── annual giving statement outbox ────────────────────────────────────────────
CREATE TABLE giving_statement_outbox (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  person_id integer NOT NULL REFERENCES people(id) ON DELETE CASCADE,
  year INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 2200),
  batch_id TEXT NOT NULL CHECK (octet_length(batch_id) BETWEEN 1 AND 64),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at TEXT,
  lease_token TEXT,
  lease_expires_at TEXT,
  last_error TEXT CHECK (last_error IS NULL OR octet_length(last_error) <= 500),
  sent_at TEXT,
  campus_id INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (person_id, year, batch_id),
  CHECK ((status = 'sending') = (lease_token IS NOT NULL AND lease_expires_at IS NOT NULL))
);
CREATE INDEX giving_statement_outbox_due ON giving_statement_outbox(status, next_attempt_at);
CREATE INDEX giving_statement_outbox_batch ON giving_statement_outbox(campus_id, batch_id);

-- ── giving audit trail (PII-free: ids, amount, currency only) ─────────────────
CREATE TABLE giving_audit_events (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  actor_person_id integer NOT NULL REFERENCES people(id),
  action TEXT NOT NULL CHECK (action IN ('manual_gift_recorded', 'fund_saved', 'statements_queued', 'gifts_exported')),
  ref_id INTEGER,
  amount_cents INTEGER,
  currency TEXT,
  campus_id INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX giving_audit_events_actor ON giving_audit_events(actor_person_id, created_at);

