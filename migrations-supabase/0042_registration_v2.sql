-- Registration v2 foundation (Postgres side of D1 migrations/0050_registration_d1.sql).
-- Adds the lifecycle, party, idempotency, and confirmation-number columns, widens the
-- status and question-type checks, and creates reg_attendees. Existing registrations get
-- a legacy submission key, one active/cancelled attendee, and a per-event confirmation
-- number in id order.

ALTER TABLE reg_events ADD COLUMN visible_from TEXT;
ALTER TABLE reg_events ADD COLUMN waitlist_enabled INTEGER NOT NULL DEFAULT 1 CHECK (waitlist_enabled IN (0,1));
ALTER TABLE reg_events ADD COLUMN confirmation_prefix TEXT
  CHECK (confirmation_prefix IS NULL OR confirmation_prefix ~ '^[A-Z0-9]{1,6}$');
ALTER TABLE reg_events ADD COLUMN next_confirmation INTEGER NOT NULL DEFAULT 1;
ALTER TABLE reg_events ADD COLUMN poster TEXT;

ALTER TABLE registrations DROP CONSTRAINT IF EXISTS registrations_status_check;
ALTER TABLE registrations ADD CONSTRAINT registrations_status_check
  CHECK (status IN ('pending','review','confirmed','waitlist','declined','cancelled'));
ALTER TABLE registrations ADD COLUMN submission_key TEXT;
ALTER TABLE registrations ADD COLUMN confirmation_no TEXT;
ALTER TABLE registrations ADD COLUMN party_size INTEGER NOT NULL DEFAULT 1 CHECK (party_size BETWEEN 1 AND 50);

ALTER TABLE reg_questions DROP CONSTRAINT IF EXISTS reg_questions_type_check;
ALTER TABLE reg_questions ADD CONSTRAINT reg_questions_type_check
  CHECK (type IN ('text','textarea','select','checkbox','yesno','section','number','date','email','phone','terms'));

-- Backfill: idempotency key first, then NOT NULL.
UPDATE registrations SET submission_key = 'legacy-' || id WHERE submission_key IS NULL;
ALTER TABLE registrations ALTER COLUMN submission_key SET NOT NULL;

-- Confirmation numbers per event in id order (prefix R + two-digit start year, 4-digit padding).
WITH numbered AS (
  SELECT r.id,
         COALESCE(e.confirmation_prefix, 'R' || substr(e.starts_at, 3, 2)) AS prefix,
         row_number() OVER (PARTITION BY r.event_id ORDER BY r.id) AS n
  FROM registrations r
  JOIN reg_events e ON e.id = r.event_id
)
UPDATE registrations
SET confirmation_no = numbered.prefix || '-' ||
  CASE WHEN numbered.n < 10 THEN '000' || numbered.n::text
       WHEN numbered.n < 100 THEN '00' || numbered.n::text
       WHEN numbered.n < 1000 THEN '0' || numbered.n::text
       ELSE numbered.n::text END
FROM numbered
WHERE registrations.id = numbered.id;

UPDATE reg_events
SET next_confirmation = COALESCE((
  SELECT max(CAST(substr(r.confirmation_no, strpos(r.confirmation_no, '-') + 1) AS INTEGER))
  FROM registrations r WHERE r.event_id = reg_events.id
), 0) + 1;

CREATE UNIQUE INDEX idx_registrations_submission ON registrations (event_id, submission_key);
CREATE UNIQUE INDEX idx_registrations_confirmation ON registrations (event_id, confirmation_no)
  WHERE confirmation_no IS NOT NULL;

CREATE TABLE reg_attendees (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  campus_id INTEGER NOT NULL DEFAULT 1,
  registration_id INTEGER NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  sort INTEGER NOT NULL DEFAULT 0,
  name TEXT NOT NULL,
  person_id INTEGER REFERENCES people(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','cancelled')),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX idx_reg_attendees_registration ON reg_attendees (registration_id);
CREATE INDEX idx_reg_attendees_person ON reg_attendees (person_id);

INSERT INTO reg_attendees (campus_id, registration_id, sort, name, person_id, status, created_at, updated_at)
SELECT campus_id, id, 0, name, person_id,
       CASE WHEN status = 'cancelled' THEN 'cancelled' ELSE 'active' END,
       created_at, updated_at
FROM registrations;

