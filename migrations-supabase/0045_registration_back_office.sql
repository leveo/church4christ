-- Registration back office (Phase 4). D1 twin: migrations/0053_registration_back_office.sql.
-- Approval and reminders on events; admin note, decision stamp, optimistic-concurrency version, refund
-- bookkeeping and payment method on registrations; a check-in table (one row per person present), a
-- per-registration activity history, per-event staff roles and an outbox for bulk email. Every addition is a
-- new defaulted or nullable column or table, so existing events and registrations keep working unchanged.

ALTER TABLE reg_events ADD COLUMN requires_approval INTEGER NOT NULL DEFAULT 0 CHECK (requires_approval IN (0,1));
ALTER TABLE reg_events ADD COLUMN reminder_days INTEGER CHECK (reminder_days IS NULL OR reminder_days BETWEEN 1 AND 30);

ALTER TABLE registrations ADD COLUMN admin_note TEXT;
ALTER TABLE registrations ADD COLUMN decided_at TEXT;
ALTER TABLE registrations ADD COLUMN decided_by INTEGER REFERENCES people(id) ON DELETE SET NULL;
ALTER TABLE registrations ADD COLUMN reminder_sent_at TEXT;
ALTER TABLE registrations ADD COLUMN version INTEGER NOT NULL DEFAULT 1;
ALTER TABLE registrations ADD COLUMN refunded_cents INTEGER NOT NULL DEFAULT 0 CHECK (refunded_cents >= 0);
ALTER TABLE registrations ADD COLUMN payment_method TEXT CHECK (payment_method IS NULL OR payment_method IN ('stripe','offline','comp'));
-- Every registration that went through Stripe Checkout was paid by card.
UPDATE registrations SET payment_method = 'stripe' WHERE stripe_checkout_session_id IS NOT NULL;

-- One row per person who is (or was) at the door. Undo deletes the row; check-out stamps checked_out_at.
CREATE TABLE reg_checkins (
  attendee_id INTEGER PRIMARY KEY REFERENCES reg_attendees(id) ON DELETE CASCADE,
  checked_in_at TEXT NOT NULL DEFAULT (datetime('now')),
  checked_in_by INTEGER REFERENCES people(id) ON DELETE SET NULL,
  checked_out_at TEXT,
  campus_id INTEGER NOT NULL DEFAULT 1
);

-- The history shown in a registration's drawer. detail_json never holds tokens or links.
CREATE TABLE reg_activity (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  campus_id INTEGER NOT NULL DEFAULT 1,
  event_id INTEGER NOT NULL REFERENCES reg_events(id) ON DELETE CASCADE,
  registration_id INTEGER NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  actor_person_id INTEGER REFERENCES people(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  detail_json TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX idx_reg_activity_registration ON reg_activity (registration_id, id);
CREATE INDEX idx_reg_activity_event ON reg_activity (event_id, id);

-- Per-event staff roles for people who have no registration admin access.
CREATE TABLE reg_event_access (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  campus_id INTEGER NOT NULL DEFAULT 1,
  event_id INTEGER NOT NULL REFERENCES reg_events(id) ON DELETE CASCADE,
  person_id INTEGER NOT NULL REFERENCES people(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('viewer','desk','registrar')),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (event_id, person_id)
);
CREATE INDEX idx_reg_event_access_person ON reg_event_access (person_id);

-- Bulk email queue. claimed_at is the drain lease: a row is claimed by stamping it while still queued, so two
-- overlapping drains never take the same row, and a claim whose sender died becomes available again.
CREATE TABLE reg_outbox (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  campus_id INTEGER NOT NULL DEFAULT 1,
  event_id INTEGER NOT NULL REFERENCES reg_events(id) ON DELETE CASCADE,
  registration_id INTEGER NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('bulk','reminder','decision')),
  subject TEXT NOT NULL,
  body TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','sent','failed','skipped')),
  attempts INTEGER NOT NULL DEFAULT 0,
  created_by INTEGER REFERENCES people(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  sent_at TEXT,
  claimed_at TEXT
);
CREATE INDEX idx_reg_outbox_status ON reg_outbox (status, id);
CREATE INDEX idx_reg_outbox_event ON reg_outbox (event_id, id);
CREATE INDEX idx_reg_outbox_registration ON reg_outbox (registration_id);

-- Keep the identity merge inventory exhaustive. Decision, check-in, activity and outbox attribution stay with
-- the person who acted; event access is a privilege, so a person holding it blocks a merge (like event_admins).
DROP TRIGGER person_merge_registry_keys_append_only_insert ON person_merge_registry_keys;
INSERT INTO person_merge_registry_keys(reference_key,policy) VALUES
  ('registrations.decided_by','historical_preserve'),
  ('reg_checkins.checked_in_by','historical_preserve'),
  ('reg_activity.actor_person_id','historical_preserve'),
  ('reg_outbox.created_by','historical_preserve'),
  ('reg_event_access.person_id','hard_conflict');
CREATE TRIGGER person_merge_registry_keys_append_only_insert BEFORE INSERT ON person_merge_registry_keys
FOR EACH ROW EXECUTE FUNCTION person_merge_registry_keys_append_only_insert_fn();
